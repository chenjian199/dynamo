HEADER = "<!--\nSPDX-FileCopyrightText: Copyright (c) 2026 HEYI. All rights reserved.\nSPDX-License-Identifier: Apache-2.0\nGenerated by python -m adapter.workflow report --catalog. DO NOT EDIT.\n-->\n\n"


def report_campaign(campaign):
    path, frozen, state = load_campaign(campaign)
    validity = freshness(frozen)
    integrity = evidence_integrity(path, frozen, state)
    text = (
        HEADER
        + "# Campaign 状态\n\n"
        + f"证据时效 `{validity}`，完整性 `{integrity['status']}`。平台 `{frozen['platform']}` / 芯片 `{frozen['chip']}` / 身份 `{frozen['identity']}`\n\n"
        + (
            "完整性错误：" + integrity.get("error", "") + "\n\n"
            if integrity.get("error")
            else ""
        )
        + "以下为留存状态；stale/invalid 时不能作为当前通过结论。\n\n| 功能 | 实施 | 任务 | 测试 | 认证 |\n| --- | --- | --- | --- | --- |\n"
    )
    for k, v in state["features"].items():
        text += f"| {k} | {v['implementation']} | {v['task']} | {v['test']} | {v['qualification']} |\n"
    (path / "report.md").write_text(text)
    return str(path / "report.md")


def evidence_integrity(path, frozen, state):
    if not any(accepted(v) for v in state["features"].values()):
        return {"status": "not_yet_qualified"}
    try:
        sealed_plan(path, frozen)
        audit_completed(path, frozen, state)
    except (ValueError, OSError, KeyError, TypeError) as exc:
        return {"status": "invalid", "error": str(exc)}
    return {"status": "valid"}


def catalog_reports(check=False):
    features = catalog()
    indexes = [
        (p, read(p))
        for p in sorted((ADAPTER / "results").glob("*/*/*/evidence-index.json"))
    ]
    modules = (
        HEADER
        + "# 模块与功能目录\n\n进度以 campaign 的独立实施、测试和认证状态为准；历史文件归类不自动产生通过项。\n\n| 功能 | 能力 | 依赖 |\n| --- | --- | --- |\n"
    )
    for key, f in features.items():
        modules += f"| [{key}]({Path(f['contract_path']).relative_to('adapter')}) | {f['name']} | {', '.join(f['dependencies']) or '环境预检'} |\n"
    matrix = (
        HEADER
        + "# 支持与证据矩阵\n\n本表显示迁移后的证据覆盖，不能把历史材料数量解释为本次认证通过。每个导入索引保留原始摘要、历史声明和路径规范化后的 SHA256；新认证必须生成独立 campaign。M10 已封存包的原验收结论见 [交付索引](releases/1.5.1-heyi-m10/index.json)。\n\n| 功能 | CUDA 历史材料 | Ascend 历史材料 | MetaX 历史材料 |\n| --- | --- | --- | --- |\n"
    )
    counts = {plat: Counter() for plat in ["cuda", "ascend", "metax"]}
    for p, index in indexes:
        if index["platform"] in counts:
            counts[index["platform"]].update(
                x["feature_id"] for x in index["artifacts"]
            )
    for key in features:
        values = [
            str(counts[p][key]) + "（待重新认证）" if counts[p][key] else "无此编号证据"
            for p in counts
        ]
        matrix += "| " + key + " | " + " | ".join(values) + " |\n"
    matrix += "\n历史使用的具体芯片、模型、日期、拓扑和版本见原始文件；芯片未统一确认的 campaign 使用 unspecified，不推断所有材料来自同一机器。\n"
    matrix += "\n## 原封存版本的验收结论\n\n这些是原发布范围内的历史结论，迁移不会撤销，也不会将其升级为新功能契约的认证。\n\n| 平台 | 引擎 | 原记录通过 | 有限 | 暂缓 |\n| --- | --- | --- | --- | --- |\n"
    for validation in sorted(
        (ADAPTER / "results").glob(
            "*/*/imported-m10/features/*/artifacts/validation.json"
        )
    ):
        receipt = read(validation)
        totals = Counter(item["status"] for item in receipt["checks"])
        matrix += f"| [{receipt['platform']}]({validation.relative_to(ADAPTER)}) | {receipt['engine_version']} | {totals['passed']} | {totals['limited']} | {totals['deferred']} |\n"
    matrix += "\n## 当前 campaign 认证\n\n| 平台 / 芯片 | 基线 | Campaign / 功能 | Case | 认证 | 时效 / 证据 |\n| --- | --- | --- | --- | --- | --- |\n"
    current_source = source_identity()
    campaigns = 0
    current_debts = []
    for lock_path in sorted((ADAPTER / "results").glob("*/*/*/lock.json")):
        path, frozen, state = load_campaign(lock_path.parent)
        campaigns += 1
        statuses = freshness_map(frozen, current_source, fingerprint)
        for key, item in state["features"].items():
            integrity = "not_qualified"
            cases = {}
            if accepted(item):
                try:
                    attempt, _ = evidence_for(path, frozen, state, key)
                    cases = {c["id"]: c for c in read(attempt / "result.json")["cases"]}
                    integrity = "valid/" + item.get("evidence_origin", "current_run")
                except (ValueError, OSError, KeyError, IndexError, TypeError):
                    integrity = "invalid"
            for case in frozen["features"][key]["cases"]:
                measured = cases.get(case["id"], {})
                assertions = measured.get("assertions", {})
                ok = bool(assertions) and all(
                    assertions.get(a, {}).get("passed") is True
                    for a in case["required_assertions"]
                )
                status = (
                    ("verified" if ok else "failed") if cases else item["qualification"]
                )
                matrix += f"| {frozen['platform']} / {frozen['chip']} | {frozen['stack']['versions']['vllm']} | [{path.name}/{key}]({path.relative_to(ADAPTER)}/state.json) | {case['id']} | {status} | {statuses[key]['freshness']} / {integrity} |\n"
            for case_id, scoped in (
                frozen["features"][key].get("case_scope", {}).items()
            ):
                if scoped["disposition"] not in {"required", "optional"}:
                    matrix += f"| {frozen['platform']} / {frozen['chip']} | {frozen['stack']['versions']['vllm']} | {path.name}/{key} | {case_id} | {scoped['disposition']} | {scoped.get('reason', '')} |\n"
            if not accepted(item) and item.get("reason"):
                latest = item.get("attempts", [{}])[-1] if item.get("attempts") else {}
                link = str(
                    (path / latest.get("path", "state.json")).relative_to(ADAPTER)
                )
                current_debts.append(
                    f"\n待办 [{path.name}/{key}]({link})：{str(item['reason']).replace('|', '/')}\n\n"
                )
    if not campaigns:
        matrix += "| — | — | 暂无按新契约完成的 campaign | — | unverified | 不把迁移视为复测 |\n"
    matrix += "\n" + "".join(current_debts)
    matrix += (
        "\n## 遗留项\n\n| 功能 | 平台 | 状态 | 原因 |\n| --- | --- | --- | --- |\n"
    )
    for issue in read(ADAPTER / "contracts/issues.yaml")["issues"]:
        matrix += f"| {issue['feature_id']} | {issue['platform']} | {issue['status']} | {issue['reason']} |\n"
    versions = (
        HEADER
        + "# 版本基线\n\n构建版本只在 `container/platforms/*.json` 中维护。每次 campaign 冻结该文件内容、环境清单、代码指纹和功能版本；版本变化需要新 campaign。旧 API 兼容可保留，不能修改厂商 vLLM 基线来迁就适配。\n\n| 平台 | 架构 | vLLM | 基础镜像 |\n| --- | --- | --- | --- |\n"
    )
    for p in sorted((ADAPTER / "platforms").glob("*/platform.yaml")):
        definition = read(p)
        stack = read(ROOT / definition["stack_profile"])
        versions += f"| {definition['id']} | {stack['architecture']} | {stack['versions']['vllm']} | `{stack['base_image']}` |\n"
    generated = {
        "modules.md": modules,
        "support-matrix.md": matrix,
        "version-baselines.md": versions,
    }
    errors = []
    for name, text in generated.items():
        p = ADAPTER / name
        if check:
            if not p.exists() or p.read_text() != text:
                errors.append(name)
        else:
            p.write_text(text)
    if errors:
        raise ValueError("Stale generated views: " + ", ".join(errors))
    return {
        "features": len(features),
        "historical_campaigns": len(indexes),
        "generated": list(generated),
    }


def release(campaign, output):
    path, _, _ = load_campaign(campaign)
    with lock(path / ".lock"):
        return _release_locked(path, output)


def _release_locked(campaign, output):
    path, frozen, state = load_campaign(campaign)
    if freshness(frozen) != "valid":
        raise ValueError(
            "Source or feature contract changed; release evidence is stale"
        )
    seal = sealed_plan(path, frozen)
    audit_completed(path, frozen, state)
    evidence, exceptions = {}, {}
    for key in frozen["planned"]:
        item = state["features"][key]
        if not accepted(item):
            if key in frozen["required"]:
                raise ValueError(f"Required feature not verified: {key}")
            exceptions[key] = {
                "scope": "optional",
                "qualification": item["qualification"],
                "reason": item.get("reason", []),
            }
            continue
        attempt, gate = evidence_for(path, frozen, state, key)
        evidence[key] = {
            "attempt": str(attempt),
            "origin": item.get("evidence_origin", "current_run"),
            "result_sha256": digest(attempt / "result.json"),
            "execution_sha256": digest(attempt / "execution.json"),
            "qualification": gate["qualification"],
            "warnings": gate.get("warnings", []),
        }
    output = Path(output).resolve()
    if not output.is_relative_to(path):
        raise ValueError("Release scope index must be stored inside the campaign")
    if Path(output).exists():
        raise ValueError("Release index already exists; never rewrite a sealed release")
    result = {
        "schema_version": 1,
        "identity": frozen["identity"],
        "scope": frozen.get("scope", frozen["required"]),
        "optional_failures": exceptions,
        "dependency_closure": frozen["planned"],
        "plan_sha256": seal["plan_sha256"],
        "evidence": evidence,
        "status": "verified_declared_scope",
        "campaign": str(path),
        "lock_sha256": digest(path / "lock.json"),
        "note": "Scope index only. Build, offline archive verification, and sealing use M02/M10 delivery scripts. No implicit full-platform certification.",
    }
    atomic(output, result)
    return result

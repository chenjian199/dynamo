"""Count a frozen Git revision with cloc; never change the working tree/index.

Requires Perl and cloc 2.06. Writes a Markdown report and per-file CSV to --output.
Only committed files are included. See classify() for the explicit scope rules.
"""

import argparse
import ast
import collections
import csv
import hashlib
import json
import re
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = {
    ".py",
    ".pyi",
    ".rs",
    ".go",
    ".sh",
    ".bash",
    ".ps1",
    ".c",
    ".h",
    ".cpp",
    ".hpp",
    ".cu",
    ".cuh",
    ".js",
    ".ts",
    ".tsx",
    ".jsx",
    ".css",
    ".scss",
    ".html",
    ".proto",
    ".bt",
    ".cmake",
    ".mk",
}
GENERATED = re.compile(
    r"(?im)^[ \t]*(?:\#|//|/\*|\*)[ \t]*"
    r"(?:code generated\b|(?:automatically generated|auto-generated) by\b|"
    r"@generated\b|this file (?:is|was) generated\b|"
    r"generated by[^\n]*(?:do not edit|DO NOT EDIT))"
)
LABELS = {
    "source": "源码、测试及构建脚本",
    "generated_source": "明确标记的生成源码",
    "vendor": "第三方 vendor 文件",
    "evidence": "结果、日志、快照及补丁",
    "docs": "文档",
    "license": "版权元数据",
    "config": "配置与结构化数据",
    "lock": "依赖锁定文件",
    "other": "其它文本/资源",
    "symlink": "符号链接",
}


def classify(path, data):
    p = Path(path)
    ext = p.suffix.lower()
    if "vendor" in p.parts or "third_party" in p.parts:
        return "vendor"
    if p.name.endswith((".license", ".LICENSE")) or p.name in {"LICENSE", "NOTICE"}:
        return "license"
    if (
        "results" in p.parts
        or "-results." in p.name
        or ext in {".log", ".csv", ".snap", ".patch", ".sse"}
    ):
        return "evidence"
    if p.name.endswith(".lock") or p.name in {"go.sum", "package-lock.json"}:
        return "lock"
    if (
        ext in SOURCE
        or "Dockerfile" in p.name
        or p.name in {"Makefile", "CMakeLists.txt"}
    ):
        head = "\n".join(data.decode("utf-8", errors="replace").splitlines()[:40])
        generated_docstring = False
        if ext == ".py" and "do not edit" in head.lower():
            try:
                doc = ast.get_docstring(ast.parse(data)) or ""
                generated_docstring = bool(
                    re.search(r"(?im)^auto-generated\b", doc)
                    and "do not edit" in doc.lower()
                )
            except (SyntaxError, ValueError):
                pass
        if (
            GENERATED.search(head)
            or generated_docstring
            or ".generated." in p.name
            or p.name.startswith("zz_generated.")
            or p.name.endswith(("_pb2.py", "_pb2.pyi", "_pb2_grpc.py"))
        ):
            return "generated_source"
        return "source"
    if ext in {".md", ".mdx", ".rst"}:
        return "docs"
    if ext in {
        ".json",
        ".jsonl",
        ".yaml",
        ".yml",
        ".toml",
        ".ini",
        ".xml",
        ".tpl",
        ".j2",
        ".jinja",
        ".env",
    }:
        return "config"
    return "other"


def module(path):
    return path.split("/")[0] if "/" in path else "(root)"


def detail_module(path):
    parts = path.split("/")
    if path.startswith("components/src/dynamo/"):
        return "/".join(parts[:4]) if len(parts) > 4 else "components/src/dynamo/(root)"
    if len(parts) > 2:
        return "/".join(parts[:2])
    return module(path)


def aggregate(rows, key):
    result = collections.defaultdict(
        lambda: dict(files=0, code=0, comment=0, blank=0, physical=0)
    )
    for row in rows:
        target = result[row[key]]
        target["files"] += 1
        for metric in ("code", "comment", "blank", "physical"):
            target[metric] += row[metric]
    return sorted(result.items(), key=lambda item: item[1]["code"], reverse=True)


def table(groups):
    lines = [
        "| 分类 | 文件 | 有效代码行 | 注释行 | 空行 | 物理行 |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for key, value in groups:
        lines.append(
            "| "
            + key
            + " | "
            + " | ".join(
                f"{value[k]:,}"
                for k in ("files", "code", "comment", "blank", "physical")
            )
            + " |"
        )
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--revision", default="HEAD")
    parser.add_argument("--cloc", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    cloc = args.cloc.resolve()
    version = subprocess.check_output(
        ["perl", str(cloc), "--version"], text=True
    ).strip()
    if version != "2.06":
        parser.error(f"Expected cloc 2.06, got {version}")
    revision = subprocess.check_output(
        ["git", "rev-parse", args.revision + "^{commit}"], cwd=ROOT, text=True
    ).strip()
    rows = []
    with tempfile.TemporaryDirectory(prefix="dynamo-project-stats-") as temp:
        base = Path(temp)
        tree = base / "tree"
        tree.mkdir()
        archive = base / "source.tar"
        subprocess.run(
            ["git", "archive", "--format=tar", "-o", str(archive), revision],
            cwd=ROOT,
            check=True,
        )
        subprocess.run(["tar", "-xf", str(archive), "-C", str(tree)], check=True)
        paths = (
            subprocess.check_output(
                ["git", "ls-tree", "-rz", "--name-only", revision], cwd=ROOT
            )
            .decode()
            .split("\0")[:-1]
        )
        selected = []
        for path in paths:
            file = tree / path
            if file.is_symlink():
                data, category = b"", "symlink"
            else:
                data = file.read_bytes()
                category = classify(path, data)
            binary = b"\0" in data
            physical = 0 if binary else len(data.splitlines())
            rows.append(
                dict(
                    path=path,
                    category=category,
                    module=module(path),
                    detail=detail_module(path),
                    language="",
                    code=0,
                    comment=0,
                    blank=0,
                    physical=physical,
                    binary=binary,
                )
            )
            if category in {"source", "generated_source"}:
                selected.append(path)
        listing = base / "files.txt"
        listing.write_text("\n".join(selected) + "\n")
        result = base / "cloc.json"
        subprocess.run(
            [
                "perl",
                str(cloc),
                "--list-file=" + str(listing),
                "--by-file",
                "--json",
                "--skip-uniqueness",
                "--timeout=0",
                "--force-lang=C,bt",
                "--out=" + str(result),
                "--quiet",
            ],
            cwd=tree,
            check=True,
        )
        counts = json.loads(result.read_text())
        for row in rows:
            if row["category"] not in {"source", "generated_source"}:
                continue
            entry = counts.get(row["path"]) or counts.get("./" + row["path"])
            if entry is None:
                if row["physical"] == 0:
                    row["language"] = {".py": "Python", ".rs": "Rust", ".go": "Go"}.get(
                        Path(row["path"]).suffix, "Empty source"
                    )
                    continue
                raise RuntimeError("cloc did not count " + row["path"])
            row.update({key: entry[key] for key in ("code", "comment", "blank")})
            row["language"] = (
                "bpftrace" if row["path"].endswith(".bt") else entry["language"]
            )
            if row["physical"] != row["code"] + row["comment"] + row["blank"]:
                raise RuntimeError("Line count mismatch: " + row["path"])
    source = [r for r in rows if r["category"] == "source"]
    generated = [r for r in rows if r["category"] == "generated_source"]
    args.output.mkdir(parents=True, exist_ok=True)
    with (args.output / "project-statistics.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    metadata = dict(
        revision=revision,
        cloc_version=version,
        cloc_sha256=hashlib.sha256(cloc.read_bytes()).hexdigest(),
        tracked_files=len(rows),
    )
    (args.output / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    report = [
        "<!--\nSPDX-FileCopyrightText: Copyright (c) 2026 HEYI. All rights reserved.\nSPDX-License-Identifier: Apache-2.0\n-->\n",
        "# Dynamo 项目代码规模\n",
        f"统计提交：`{revision}`；受 Git 管理文件 **{len(rows):,}** 个；工具 cloc {version}。",
        "\n## 统计口径\n",
        "- 统计指定提交的完整源码，包含上游和 HEYI 代码；不是适配增量，也不是人日估算。",
        "- 有效代码行使用 cloc 的 code 字段，排除注释和空行；Python 文档字符串按 cloc 默认规则计入注释。物理行包含代码、注释和空行。",
        "- 主表包含测试、示例、基准、适配工具、网站组件、协议定义、Dockerfile/Makefile/CMake 等构建代码。YAML/JSON/TOML 等配置与数据单列。",
        "- 不纳入未跟踪 reference/、模型、缓存和编译目录；符号链接不跟随。独立路径即使内容相同也分别计数。",
        "- vendor/third_party 单列；results 目录、结果文件、日志、CSV、快照、补丁不计作源码。没有标记的生成文件不能自动可靠识别，不能把主表等同于全部手写代码。",
        "- 明确生成标记（前 40 行）及生成文件命名的源码单列；bpftrace 使用 C 注释规则解析并单独命名。",
        "- 非源码类别只统计文件数与文本物理行，不把 JSON 数据或文档内容称为有效代码；二进制文件记文件数不记行数。",
        "- 本次新增统计工具与报告不在被统计提交中。复现命令会在输出目录生成逐文件 project-statistics.csv 和 metadata.json；仓库仅保留此汇总报告。",
        "\n## 源码总数\n",
        table(aggregate([dict(r, total="全部源码") for r in source], "total")),
        "\n包含明确生成源码时的总数：\n",
        table(
            aggregate(
                [dict(r, total="源码 + 生成源码") for r in source + generated], "total"
            )
        ),
        "\n## 按语言\n",
        table(aggregate(source, "language")),
        "\n## 按一级目录\n",
        table(aggregate(source, "module")),
        "\n## 按大模块展开\n",
        table(aggregate(source, "detail")),
        "\n## 生成源码（不在上述主表内）\n",
        table(aggregate(generated, "language")),
        "\n## 全部文件分类\n",
        "| 类别 | 文件数 | 文本物理行 |",
        "| --- | ---: | ---: |",
    ]
    for category, values in aggregate(rows, "category"):
        report.append(
            f"| {LABELS[category]} | {values['files']:,} | {values['physical']:,} |"
        )
    report += [
        "\n## 复现\n",
        "```bash",
        "curl -fL https://raw.githubusercontent.com/AlDanial/cloc/v2.06/cloc -o /tmp/cloc-2.06.pl",
        f"python3 adapter/tools/project-stats.py --revision {revision} \\\n  --cloc /tmp/cloc-2.06.pl --output /tmp/dynamo-project-statistics",
        "```",
        f"\ncloc SHA256：`{metadata['cloc_sha256']}`。脚本不修改 Git index 或工作树，只向指定输出目录写入统计产物。",
    ]
    (args.output / "project-statistics.md").write_text("\n".join(report) + "\n")
    print(
        json.dumps(
            dict(
                metadata,
                source_totals=aggregate(
                    [dict(r, total="source") for r in source], "total"
                ),
            ),
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
